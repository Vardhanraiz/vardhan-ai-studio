def _extract_entities_from_prompt(prompt: str) -> list[str]:
    lower = prompt.lower()
    candidates = [
        ("employees", ["employee", "staff", "hr", "worker"]),
        ("departments", ["department", "team", "division"]),
        ("products", ["product", "inventory", "catalog", "item", "shop", "store"]),
        ("orders", ["order", "invoice", "billing", "sale"]),
        ("patients", ["patient", "clinic", "hospital", "medical", "doctor"]),
        ("appointments", ["appointment", "booking", "schedule"]),
        ("students", ["student", "course", "school", "college", "grade"]),
        ("tasks", ["task", "todo", "ticket", "issue", "kanban"]),
        ("customers", ["customer", "client", "crm", "contact"]),
    ]
    found = [name for name, kws in candidates if any(kw in lower for kw in kws)]
    if not found:
        found = ["items"]
    return found[:4]


def _sql_schema_for_entities(entities: list[str], database_type: str) -> str:
    id_col = {
        "SQLite": "INTEGER PRIMARY KEY AUTOINCREMENT",
        "PostgreSQL": "SERIAL PRIMARY KEY",
        "SQL Server": "INT IDENTITY(1,1) PRIMARY KEY",
    }.get(database_type, "INTEGER PRIMARY KEY AUTOINCREMENT")

    lines = [
        f"-- Generated by Vardhan AI Studio App Builder ({database_type})",
        "",
        "CREATE TABLE IF NOT EXISTS users (",
        f"    id {id_col},",
        "    full_name VARCHAR(120) NOT NULL,",
        "    email VARCHAR(160) UNIQUE NOT NULL,",
        "    password_hash VARCHAR(255) NOT NULL,",
        "    role VARCHAR(32) NOT NULL DEFAULT 'user',",
        "    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP",
        ");",
        "",
    ]

    for entity in entities:
        if entity == "departments":
            lines.extend(
                [
                    "CREATE TABLE IF NOT EXISTS departments (",
                    f"    id {id_col},",
                    "    name VARCHAR(120) UNIQUE NOT NULL,",
                    "    manager_name VARCHAR(120) DEFAULT '',",
                    "    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP",
                    ");",
                    "",
                ]
            )
        elif entity == "employees":
            fk_line = (
                "    department_id INTEGER REFERENCES departments(id),"
                if "departments" in entities
                else "    department VARCHAR(120) DEFAULT 'General',"
            )
            lines.extend(
                [
                    "CREATE TABLE IF NOT EXISTS employees (",
                    f"    id {id_col},",
                    "    full_name VARCHAR(120) NOT NULL,",
                    "    email VARCHAR(160) UNIQUE NOT NULL,",
                    "    role_title VARCHAR(120) NOT NULL,",
                    fk_line,
                    "    status VARCHAR(32) NOT NULL DEFAULT 'active',",
                    "    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP",
                    ");",
                    "",
                ]
            )
        else:
            lines.extend(
                [
                    f"CREATE TABLE IF NOT EXISTS {entity} (",
                    f"    id {id_col},",
                    "    name VARCHAR(160) NOT NULL,",
                    "    description TEXT DEFAULT '',",
                    "    status VARCHAR(32) NOT NULL DEFAULT 'active',",
                    "    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP",
                    ");",
                    "",
                ]
            )
    return "\n".join(lines)


def _generate_fastapi_backend(app_name: str, primary_entity: str) -> str:
    return f'''"""Auto-generated FastAPI + SQLite backend for {app_name}."""

from __future__ import annotations

import hashlib
import sqlite3
from pathlib import Path
from typing import Optional

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

BASE_DIR = Path(__file__).resolve().parent
DB_PATH = BASE_DIR / "app.db"
SCHEMA_PATH = BASE_DIR.parent / "database" / "schema.sql"

app = FastAPI(title="{app_name}", version="1.0.0")
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)


def get_conn() -> sqlite3.Connection:
    conn = sqlite3.connect(str(DB_PATH))
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON;")
    return conn


def init_db() -> None:
    conn = get_conn()
    try:
        if SCHEMA_PATH.exists():
            conn.executescript(SCHEMA_PATH.read_text(encoding="utf-8"))
        conn.commit()
    finally:
        conn.close()


init_db()


class RegisterRequest(BaseModel):
    full_name: str = Field(..., min_length=2)
    email: str = Field(..., min_length=4)
    password: str = Field(..., min_length=6)


class LoginRequest(BaseModel):
    email: str
    password: str


class RecordCreate(BaseModel):
    name: str = Field(..., min_length=1)
    description: str = ""
    status: str = "active"


@app.get("/api/health")
def health() -> dict[str, str]:
    return {{"status": "ok", "app": "{app_name}"}}


@app.post("/api/auth/register", status_code=201)
def register(payload: RegisterRequest) -> dict[str, object]:
    pw_hash = hashlib.sha256(payload.password.encode("utf-8")).hexdigest()
    conn = get_conn()
    try:
        cur = conn.execute(
            "INSERT INTO users (full_name, email, password_hash) VALUES (?, ?, ?)",
            (payload.full_name.strip(), payload.email.strip().lower(), pw_hash),
        )
        conn.commit()
        return {{"id": cur.lastrowid, "full_name": payload.full_name, "email": payload.email}}
    except sqlite3.IntegrityError as exc:
        raise HTTPException(status_code=409, detail="Email already registered") from exc
    finally:
        conn.close()


@app.post("/api/auth/login")
def login(payload: LoginRequest) -> dict[str, object]:
    pw_hash = hashlib.sha256(payload.password.encode("utf-8")).hexdigest()
    conn = get_conn()
    try:
        row = conn.execute(
            "SELECT id, full_name, email, role FROM users WHERE email = ? AND password_hash = ?",
            (payload.email.strip().lower(), pw_hash),
        ).fetchone()
        if not row:
            raise HTTPException(status_code=401, detail="Invalid email or password")
        return dict(row)
    finally:
        conn.close()


@app.get("/api/{primary_entity}")
def list_records() -> list[dict[str, object]]:
    conn = get_conn()
    try:
        rows = conn.execute("SELECT * FROM {primary_entity} ORDER BY id DESC").fetchall()
        return [dict(r) for r in rows]
    finally:
        conn.close()


@app.post("/api/{primary_entity}", status_code=201)
def create_record(payload: RecordCreate) -> dict[str, object]:
    conn = get_conn()
    try:
        cols = [r["name"] for r in conn.execute("PRAGMA table_info({primary_entity})").fetchall()]
        if "full_name" in cols:
            cur = conn.execute(
                "INSERT INTO {primary_entity} (full_name, email, role_title, status) VALUES (?, ?, ?, ?)",
                (payload.name, f"{{payload.name.lower().replace(' ', '.')}}@example.com", payload.description or "Member", payload.status),
            )
        else:
            cur = conn.execute(
                "INSERT INTO {primary_entity} (name, description, status) VALUES (?, ?, ?)",
                (payload.name, payload.description, payload.status),
            )
        conn.commit()
        row = conn.execute("SELECT * FROM {primary_entity} WHERE id = ?", (cur.lastrowid,)).fetchone()
        return dict(row)
    finally:
        conn.close()


@app.delete("/api/{primary_entity}/{{record_id}}", status_code=204)
def delete_record(record_id: int) -> None:
    conn = get_conn()
    try:
        cur = conn.execute("DELETE FROM {primary_entity} WHERE id = ?", (record_id,))
        conn.commit()
        if cur.rowcount == 0:
            raise HTTPException(status_code=404, detail="Record not found")
    finally:
        conn.close()
'''


def _generate_node_backend(app_name: str, primary_entity: str) -> str:
    return f'''// Auto-generated Node.js HTTP API for {app_name}
import http from "node:http";

const records = [];
let nextId = 1;

const server = http.createServer((req, res) => {{
  res.setHeader("Content-Type", "application/json");
  res.setHeader("Access-Control-Allow-Origin", "*");
  if (req.url === "/api/health" && req.method === "GET") {{
    res.end(JSON.stringify({{ status: "ok", app: "{app_name}" }}));
    return;
  }}
  if (req.url === "/api/{primary_entity}" && req.method === "GET") {{
    res.end(JSON.stringify(records));
    return;
  }}
  if (req.url === "/api/{primary_entity}" && req.method === "POST") {{
    let body = "";
    req.on("data", (c) => (body += c));
    req.on("end", () => {{
      const parsed = JSON.parse(body || "{{}}");
      const item = {{ id: nextId++, name: parsed.name || "Untitled", description: parsed.description || "", status: "active" }};
      records.push(item);
      res.statusCode = 201;
      res.end(JSON.stringify(item));
    }});
    return;
  }}
  res.statusCode = 404;
  res.end(JSON.stringify({{ error: "Not found" }}));
}});

server.listen(8001, "127.0.0.1", () => console.log("{app_name} API running on http://127.0.0.1:8001"));
'''


def _generate_aspnet_backend(app_name: str, primary_entity: str) -> str:
    return f'''// Auto-generated ASP.NET Core Minimal API for {app_name}
var builder = WebApplication.CreateBuilder(args);
var app = builder.Build();

var records = new List<RecordItem>();

app.MapGet("/api/health", () => Results.Ok(new {{ status = "ok", app = "{app_name}" }}));
app.MapGet("/api/{primary_entity}", () => Results.Ok(records));
app.MapPost("/api/{primary_entity}", (RecordItem item) => {{
    records.Add(item);
    return Results.Created($"/api/{primary_entity}/{{item.Id}}", item);
}});

app.Run();

record RecordItem(int Id, string Name, string Description, string Status);
'''


