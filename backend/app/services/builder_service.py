def build_application_from_prompt(
    db: Session,
    *,
    app_name: str,
    prompt: str,
    frontend_stack: str,
    backend_stack: str,
    database_stack: str,
    settings: Settings,
) -> dict[str, Any]:
    """Generate real project files inside workspace/, run real checks, and register project."""
    entities = _extract_entities_from_prompt(prompt)
    primary_entity = entities[0]
    tech_stack = f"{frontend_stack}, {backend_stack}, {database_stack}"

    project = project_service.create_project(
        db,
        ProjectCreate(
            name=app_name.strip(),
            description=prompt.strip()[:1000],
            tech_stack=tech_stack,
        ),
        settings.workspace_root,
    )

    project_dir = file_service.get_project_root(project.relative_path, settings.workspace_root)
    files_to_create: dict[str, str] = {}

    schema_sql = _sql_schema_for_entities(entities, database_stack)
    files_to_create["database/schema.sql"] = schema_sql

    if backend_stack == "Python FastAPI":
        files_to_create["backend/__init__.py"] = ""
        files_to_create["backend/main.py"] = _generate_fastapi_backend(app_name, primary_entity)
        files_to_create["backend/requirements.txt"] = "fastapi>=0.115.0\nuvicorn>=0.30.0\npydantic>=2.7.0\npytest>=8.2.0\nhttpx>=0.27.0\n"
        files_to_create["tests/test_api.py"] = _generate_pytest_suite(primary_entity)
        run_backend_cmd = "uvicorn backend.main:app --host 127.0.0.1 --port 8001 --reload"
    elif backend_stack == "Node.js":
        files_to_create["backend/server.mjs"] = _generate_node_backend(app_name, primary_entity)
        files_to_create["backend/package.json"] = '{\n  "name": "generated-api",\n  "type": "module",\n  "scripts": { "start": "node server.mjs" }\n}\n'
        run_backend_cmd = "node backend/server.mjs"
    else:
        files_to_create["backend/Program.cs"] = _generate_aspnet_backend(app_name, primary_entity)
        run_backend_cmd = "dotnet run --project backend"

    files_to_create["frontend/index.html"] = _generate_frontend_html(
        app_name, prompt, primary_entity, entities
    )
    if frontend_stack == "React":
        files_to_create["frontend/App.tsx"] = (
            f'// React starter component for {app_name}\n'
            f'export default function App() {{\n'
            f'  return <main className="p-6"><h1>{app_name}</h1><p>Connected to /api/{primary_entity}</p></main>;\n'
            f'}}\n'
        )

    files_to_create["README.md"] = (
        f"# {app_name}\n\n"
        f"Generated by **Vardhan AI Studio** App Builder.\n\n"
        f"## Prompt\n{prompt}\n\n"
        f"## Selected Stack\n- Frontend: {frontend_stack}\n- Backend: {backend_stack}\n- Database: {database_stack}\n\n"
        f"## Modules & Tables\n" + "\n".join(f"- `{e}`" for e in ["users", *entities]) + "\n\n"
        f"## How to Run\n1. Start backend: `{run_backend_cmd}`\n2. Open `frontend/index.html` or use the built-in Preview pane.\n"
    )

    created_paths: list[str] = []
    for rel_path, content in files_to_create.items():
        file_service.create_project_entry(
            db,
            project_rel_path=project.relative_path,
            file_rel_path=rel_path,
            entry_type="file",
            content=content,
            workspace_root=settings.workspace_root,
            actor="app_builder",
            overwrite=True,
            backup_root=settings.backup_dir,
        )
        created_paths.append(rel_path)

    # Real verification checks (never claim complete without checking generated files!)
    checks: list[dict[str, Any]] = []

    all_exist = all((project_dir / p).is_file() for p in created_paths)
    checks.append(
        {
            "name": "file_existence",
            "passed": all_exist,
            "detail": f"Verified {len(created_paths)}/{len(created_paths)} generated files on disk.",
        }
    )

    if backend_stack == "Python FastAPI":
        try:
            py_compile.compile(str(project_dir / "backend" / "main.py"), doraise=True)
            py_compile.compile(str(project_dir / "tests" / "test_api.py"), doraise=True)
            checks.append({"name": "python_syntax", "passed": True, "detail": "Compiled backend/main.py and tests/test_api.py cleanly."})
        except py_compile.PyCompileError as exc:
            checks.append({"name": "python_syntax", "passed": False, "detail": str(exc)})

    if database_stack == "SQLite":
        db_file = project_dir / "backend" / "app.db"
        db_file.parent.mkdir(parents=True, exist_ok=True)
        try:
            conn = sqlite3.connect(str(db_file))
            conn.executescript(schema_sql)
            tables = [
                r[0]
                for r in conn.execute(
                    "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
                ).fetchall()
            ]
            conn.close()
            checks.append(
                {
                    "name": "sqlite_schema_init",
                    "passed": len(tables) >= 2,
                    "detail": f"Initialized SQLite database backend/app.db with tables: {', '.join(tables)}.",
                }
            )
            created_paths.append("backend/app.db")
        except sqlite3.Error as exc:
            checks.append({"name": "sqlite_schema_init", "passed": False, "detail": str(exc)})

    all_passed = all(c["passed"] for c in checks)
    record_audit_event(
        db,
        action="builder.generate_app",
        actor="app_builder",
        target_path=project.relative_path,
        status="success" if all_passed else "partial",
        details={"files": len(created_paths), "checks_passed": all_passed, "stack": tech_stack},
    )

    return {
        "project": {
            "id": project.id,
            "name": project.name,
            "slug": project.slug,
            "relative_path": project.relative_path,
            "tech_stack": project.tech_stack,
        },
        "entities": ["users", *entities],
        "created_files": created_paths,
        "preview_file": "frontend/index.html",
        "checks": checks,
        "verified": all_passed,
        "run_instructions": [
            f"cd workspace/{project.relative_path}",
            run_backend_cmd,
            "Open frontend/index.html in browser or click Preview in Vardhan AI Studio",
        ],
    }
